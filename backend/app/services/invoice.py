"""Generate a simple PDF invoice for an order using reportlab."""
from __future__ import annotations

import io

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.pdfgen import canvas

from app.models.order import Order


def build_invoice_pdf(order: Order) -> bytes:
    buf = io.BytesIO()
    c = canvas.Canvas(buf, pagesize=A4)
    width, height = A4
    left = 20 * mm
    right = width - 20 * mm
    y = height - 25 * mm

    # Header
    c.setFillColor(colors.HexColor("#4f46e5"))
    c.setFont("Helvetica-Bold", 22)
    c.drawString(left, y, "BookExpert")
    c.setFillColor(colors.black)
    c.setFont("Helvetica", 10)
    c.drawRightString(right, y, "INVOICE")
    c.setFont("Helvetica-Bold", 13)
    c.drawRightString(right, y - 16, order.order_number)
    y -= 36
    c.setFillColor(colors.HexColor("#6b7280"))
    c.setFont("Helvetica", 9)
    c.drawString(left, y, "Sales & Inventory Management System")
    c.setFillColor(colors.black)

    # Meta block
    y -= 28
    c.setFont("Helvetica-Bold", 10)
    c.drawString(left, y, "Bill To")
    c.drawString(right - 170, y, "Order Details")
    c.setFont("Helvetica", 10)
    y -= 15
    c.drawString(left, y, order.customer.name)
    c.drawString(right - 170, y, f"Status: {order.status.value.replace('_', ' ')}")
    y -= 14
    c.drawString(left, y, order.customer.email or "")
    c.drawString(right - 170, y,
                 f"Date: {order.created_at.strftime('%Y-%m-%d %H:%M')}")
    if order.customer.address:
        y -= 14
        c.drawString(left, y, order.customer.address[:60])
    y -= 14
    c.drawString(right - 170, y, f"Raised by: {order.created_by.name}")

    # Line-item table header
    y -= 30
    c.setFillColor(colors.HexColor("#f3f4f6"))
    c.rect(left, y - 4, right - left, 20, fill=1, stroke=0)
    c.setFillColor(colors.HexColor("#374151"))
    c.setFont("Helvetica-Bold", 9)
    col_qty = right - 150
    col_unit = right - 95
    col_line = right
    c.drawString(left + 4, y + 2, "PRODUCT")
    c.drawRightString(col_qty, y + 2, "QTY")
    c.drawRightString(col_unit, y + 2, "UNIT")
    c.drawRightString(col_line, y + 2, "AMOUNT")
    c.setFillColor(colors.black)
    c.setFont("Helvetica", 10)

    y -= 20
    for item in order.items:
        name = item.product.name
        if len(name) > 48:
            name = name[:45] + "..."
        c.drawString(left + 4, y, name)
        c.drawRightString(col_qty, y, str(item.quantity))
        c.drawRightString(col_unit, y, f"${item.unit_price:,.2f}")
        c.drawRightString(col_line, y, f"${item.line_total:,.2f}")
        y -= 18
        if y < 40 * mm:  # new page if we run out of room
            c.showPage()
            y = height - 25 * mm

    # Total
    y -= 6
    c.line(col_unit - 10, y, right, y)
    y -= 18
    c.setFont("Helvetica-Bold", 12)
    c.drawRightString(col_unit, y, "TOTAL")
    c.drawRightString(col_line, y, f"${order.total_amount:,.2f}")

    # Footer
    c.setFont("Helvetica-Oblique", 8)
    c.setFillColor(colors.HexColor("#9ca3af"))
    c.drawString(left, 20 * mm, "Thank you for your business — generated by BookExpert SIMS.")

    c.showPage()
    c.save()
    return buf.getvalue()
